# -*- coding: utf-8 -*-
"""P0_PM A0-3: implementation layer vs metric-limit comparison on the same
torus (implementation entropy cost).

Same affine torus (edge_alphabet_affine_check.build_honeycomb_torus; identical
graph, edge set and face cycle order as the pure-metric counter of the
torus-growth series):
  metric-limit layer (pure metric): each edge assigned independently from the
  alphabet, only the two per-face closure equations checked;
  implementation layer (arm numbers): each face receives one build_library tile
  (fixed edge-value sequence); constraints =
  (1) shared edges take the same value (enforced automatically by the global
      edge assignment);
  (2) when all three edge weights at a vertex are in place, check the
      vertex_feasible existence interval any(n6<=c<=n6+n5 for c in allowed)
      (physical-legality scope = measure cross-check v2);
  (3) all-5 tiles are not adjacent (max_c3<=1 alphabets);
  (4) at completion, a multi-slot Kuhn matching over arm directions (every
      weight-5 edge direction globally realizable; replicates the v2 fixed
      version).

Comparison (implementation alphabet = arm-number alphabet; the edge-value
domain is generated by the arm pairs):
  impl quaternary {222,223,233,333} => edge values {4,5,6} = translation image
    of metric {0,1,2}; its vertex-interval / arms constraints are automatically
    satisfied on the allowed set {0,1,2,3} => Omega == metric bit-for-bit
    (zero implementation cost; independent-path cross-validation);
  impl binary {222,223} => edge values still {4,5,6} (223 contains arm 3, so
    3+3=6 can occur), but the vertex c3 in {0,1} contraction => Omega < metric
    = the implementation entropy cost.
Implementation entropy cost = Omega_impl / Omega_metric.

Anchors (must pass):
  single-species {222}/{333} torus 2x2/3x2/3x3: Omega = 1;
  {222,223} 2x2: DFS vs full enumeration of library combinations on the
  affine graph (brute force);
  impl Omega <= metric Omega at every size.

Output: P0_PM_implementation_constraint_comparison.csv
Memory: DFS counts only, never materializes solutions, <10 MB; brute force on
small cases <50 MB; workstation run.
"""
import csv
import itertools
import math
import sys
import time
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pseudocrystal_lib as pl                                    # noqa: E402
from edge_alphabet_affine_check import build_honeycomb_torus, count_assignments  # noqa: E402

OUT_CSV = HERE / "P0_PM_implementation_constraint_comparison.csv"
SIZES = [(2, 2), (3, 2), (3, 3)]
METRIC_ALPHABETS = [("metric-binary", (0, 1)), ("metric-arith", (0, 1, 2))]
IMPL_ALPHABETS = [("impl-binary", ("222", "223")),
                  ("impl-quaternary", ("222", "223", "233", "333"))]


def impl_count(Lx, Ly, alphabet):
    """Exact implementation-layer (arm-number tile) counting on the affine torus."""
    edge_set, faces = build_honeycomb_torus(Lx, Ly)
    E = len(edge_set)
    lib = pl.build_library(alphabet)
    libw = lib.weights
    lib_ay = lib.all_yellow
    allowed = lib.allowed_c3
    K = lib.size
    enforce_ay = max(allowed) <= 1
    max_c3 = max(allowed)
    vertices = set()
    for u, v in edge_set:
        vertices.add(u)
        vertices.add(v)
    adj = {v: [] for v in vertices}
    for ei, (u, v) in enumerate(edge_set):
        adj[u].append(ei)
        adj[v].append(ei)
    edge_faces = defaultdict(list)
    for fi, f in enumerate(faces):
        for e in f:
            edge_faces[e].append(fi)
    vals = [None] * E
    sol = {}
    count = 0

    def arms_ok():
        """Final multi-slot Kuhn matching over weight-5 edge directions
        (replicates the v2 multi-slot fixed version)."""
        cap = defaultdict(int)
        verts = set()
        fives = []
        for e, w in enumerate(vals):
            u, v = edge_set[e]
            verts.add(u)
            verts.add(v)
            if w == 6:
                cap[u] -= 1
                cap[v] -= 1
            elif w == 5:
                fives.append((u, v))
        for v in verts:
            cap[v] += max_c3
        if any(cap[v] < 0 for v in verts):
            return False
        slots = {v: [None] * cap[v] for v in verts}

        def try_k(e, visited):
            for v in e:
                if v in visited:
                    continue
                visited.add(v)
                for si in range(len(slots[v])):
                    occ = slots[v][si]
                    if occ is None or try_k(occ, visited):
                        slots[v][si] = e
                        return True
            return False

        for e in fives:
            if not try_k(e, set()):
                return False
        return True

    def rec(fi):
        nonlocal count
        if fi == len(faces):
            if arms_ok():
                count += 1
            return
        f = faces[fi]
        for t in range(K):
            w = libw[t]
            ok = True
            for pos_i, e in enumerate(f):        # (1) shared edge same value
                if vals[e] is not None and vals[e] != int(w[pos_i]):
                    ok = False
                    break
            if ok and enforce_ay and lib_ay[t]:  # (3) all-5 no adjacency
                for e in f:
                    for gj in edge_faces[e]:
                        if gj in sol and lib_ay[sol[gj]]:
                            ok = False
                            break
                    if not ok:
                        break
            if not ok:
                continue
            touched = set()
            new_edges = [e for e in f if vals[e] is None]
            for pos_i, e in enumerate(f):        # placement
                vals[e] = int(w[pos_i])
                u, v = edge_set[e]
                touched.add(u)
                touched.add(v)
            sol[fi] = t
            for u in touched:                    # (2) vertex three-edge-complete existence-interval check
                ws = [vals[ei] for ei in adj[u]]
                if all(x is not None for x in ws):
                    n6 = ws.count(6)
                    n5 = ws.count(5)
                    if not any(n6 <= c <= n6 + n5 for c in allowed):
                        ok = False
                        break
            if ok:
                rec(fi + 1)
            del sol[fi]
            for e in new_edges:                  # undo only this face's newly assigned edges
                vals[e] = None

    t0 = time.time()
    rec(0)
    return count, time.time() - t0


def impl_brute(Lx, Ly, alphabet):
    """Small-case brute force: full enumeration of K^F library combinations
    (independent implementation, same four constraints)."""
    edge_set, faces = build_honeycomb_torus(Lx, Ly)
    F = len(faces)
    lib = pl.build_library(alphabet)
    libw = lib.weights
    lib_ay = lib.all_yellow
    allowed = lib.allowed_c3
    K = lib.size
    max_c3 = max(allowed)
    vertices = set()
    for u, v in edge_set:
        vertices.add(u)
        vertices.add(v)
    adj = {v: [] for v in vertices}
    for ei, (u, v) in enumerate(edge_set):
        adj[u].append(ei)
        adj[v].append(ei)
    edge_faces = defaultdict(list)
    for fi, f in enumerate(faces):
        for e in f:
            edge_faces[e].append(fi)
    count = 0
    for combo in itertools.product(range(K), repeat=F):
        sol = dict(enumerate(combo))
        vals = [None] * len(edge_set)
        ok = True
        for fi, t in sol.items():
            w = libw[t]
            for pos_i, e in enumerate(faces[fi]):
                if vals[e] is None:
                    vals[e] = int(w[pos_i])
                elif vals[e] != int(w[pos_i]):
                    ok = False
                    break
            if not ok:
                break
        if not ok:
            continue
        for u in vertices:
            ws = [vals[ei] for ei in adj[u]]
            n6 = ws.count(6)
            n5 = ws.count(5)
            if not any(n6 <= c <= n6 + n5 for c in allowed):
                ok = False
                break
        if not ok:
            continue
        if max(allowed) <= 1:
            for fi, t in sol.items():
                if not lib_ay[t]:
                    continue
                for e in faces[fi]:
                    for gj in edge_faces[e]:
                        if gj != fi and lib_ay[sol[gj]]:
                            ok = False
                            break
                    if not ok:
                        break
                if not ok:
                    break
            if not ok:
                continue
        # multi-slot Kuhn over arm directions
        cap = defaultdict(int)
        fives = []
        for e, w in enumerate(vals):
            u, v = edge_set[e]
            if w == 6:
                cap[u] -= 1
                cap[v] -= 1
            elif w == 5:
                fives.append((u, v))
        for v in vertices:
            cap[v] += max_c3
        if any(cap[v] < 0 for v in vertices):
            continue
        slots = {v: [None] * cap[v] for v in vertices}

        def try_k(e, visited):
            for v in e:
                if v in visited:
                    continue
                visited.add(v)
                for si in range(len(slots[v])):
                    occ = slots[v][si]
                    if occ is None or try_k(occ, visited):
                        slots[v][si] = e
                        return True
            return False

        good = True
        for e in fives:
            if not try_k(e, set()):
                good = False
                break
        if good:
            count += 1
    return count


if __name__ == '__main__':
    print(f'= P0_PM A0-3 implementation-layer comparison (same affine graph) '
          f'{time.strftime("%m-%d %H:%M:%S")} =', flush=True)
    rows = []
    # anchor 1: single species Omega=1
    for alph in [("222",), ("333",)]:
        for (Lx, Ly) in SIZES:
            c, dt = impl_count(Lx, Ly, alph)
            tag = 'PASS' if c == 1 else 'FAIL'
            print(f'  [{tag}] single {alph} {Lx}x{Ly}: Omega={c} ({dt:.1f}s)',
                  flush=True)
            assert c == 1
    # anchor 2: {222,223} 2x2 DFS vs brute force
    c_dfs, dt = impl_count(2, 2, ("222", "223"))
    c_br = impl_brute(2, 2, ("222", "223"))
    tag = 'PASS' if c_dfs == c_br else 'FAIL'
    print(f'  [{tag}] brute (222,223) 2x2: DFS={c_dfs} brute={c_br} ({dt:.1f}s)',
          flush=True)
    assert c_dfs == c_br
    print('anchors PASS', flush=True)

    # pure-metric side (same-graph counter)
    metric_vals = {}
    for name, alpha in METRIC_ALPHABETS:
        for (Lx, Ly) in SIZES:
            omega = count_assignments(Lx, Ly, alpha)
            metric_vals[(name, Lx, Ly)] = omega
            rows.append(dict(layer=name, alphabet='+'.join(map(str, alpha)),
                             Lx=Lx, Ly=Ly, F=Lx * Ly, Omega=omega,
                             lnOmega=round(math.log(omega), 6),
                             lnOmega_per_F=round(math.log(omega) / (Lx * Ly), 6),
                             ratio_vs_metric='', seconds=''))
            print(f'  {name} {alpha} {Lx}x{Ly}: Omega={omega}', flush=True)
    # implementation layer
    impl_vals = {}
    for name, alpha in IMPL_ALPHABETS:
        for (Lx, Ly) in SIZES:
            omega, dt = impl_count(Lx, Ly, alpha)
            impl_vals[(name, Lx, Ly)] = omega
            rows.append(dict(layer=name, alphabet='+'.join(alpha),
                             Lx=Lx, Ly=Ly, F=Lx * Ly, Omega=omega,
                             lnOmega=round(math.log(omega), 6),
                             lnOmega_per_F=round(math.log(omega) / (Lx * Ly), 6),
                             ratio_vs_metric='', seconds=round(dt, 1)))
            print(f'  {name} {alpha} {Lx}x{Ly}: Omega={omega} ({dt:.1f}s)',
                  flush=True)
    # anchor 3: the quaternary implementation constraints are automatically
    # satisfied => Omega == metric {0,1,2} bit-for-bit (independent-path cross-
    # validation; consistent with the convention that the quaternary library
    # contains only closure + pair constraints);
    # the binary {222,223} (c3 in {0,1}, same edge-value domain {4,5,6})
    # contracts strictly = the implementation entropy cost
    for (Lx, Ly) in SIZES:
        m3 = metric_vals[("metric-arith", Lx, Ly)]
        i1 = impl_vals[("impl-binary", Lx, Ly)]
        i4 = impl_vals[("impl-quaternary", Lx, Ly)]
        assert i4 == m3, f'quaternary impl != metric at {Lx}x{Ly}: {i4} vs {m3}'
        assert i1 <= m3, f'impl>metric at {Lx}x{Ly}'
        print(f'  [PASS] {Lx}x{Ly}: quaternary == metric-arith ({i4}); '
              f'binary {i1} <= {m3} (ratio {i1/m3:.4f})', flush=True)
        for row in rows:
            if (row["Lx"], row["Ly"]) == (Lx, Ly):
                if row["layer"] == "impl-binary":
                    row["ratio_vs_metric"] = round(i1 / m3, 6)
                elif row["layer"] == "impl-quaternary":
                    row["ratio_vs_metric"] = round(i4 / m3, 6)
    with open(OUT_CSV, 'w', newline='', encoding='utf-8-sig') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f'done, CSV -> {OUT_CSV}', flush=True)
