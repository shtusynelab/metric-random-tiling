"""
rth_strip_tm.py - 3.4.6.4 strip transfer matrix: falsification instrument
for the perimeter law / stripe parameterization (H1).

Question: is the finite-alphabet count of 3.4.6.4 generated by O(L) stripe
parameters?
  H1 predicts: lambda(W) = lim_L Omega(W,L)^{1/L} is bounded (does not grow
  with W);
  positive entropy predicts: ln lambda(W) ~ 6*s*W grows linearly.
The perimeter law from the four-point torus counts converts to the
prediction lambda(W) ~ e^{1.14} ~ 3.13 (c' = 1.14, from
lnOmega_torus ~ 2.28L => the open-boundary strip coefficient is half).

Method:
  - patch geometry reuses PlaneRTH (W x L open boundary, 30-degree direction
    lattice, all-ones anchor built in);
  - column partitioning: face column = max j over neighboring hexagons
    (centroid distance < 2); hexagons themselves take column = j; scan along
    j = 0..L-1, closing face by face within a column;
  - closure check: directions lie in the 30-degree lattice => each edge
    carries coefficients (2Re cos, 2 sqrt(3) part, 2Re sin, 2 sqrt(3) part)
    in Z^4, and face closure = 4 integer-coefficient linear equations
    (exact, no floating-point decisions);
  - state = value vector of the active edges (assigned, still having
    unprocessed faces); the active-edge set at the end of a column is fixed
    by geometry => key = fixed-length value tuple; intra-column intermediate
    states use sorted (eid, val) tuples.
Anchors: DP counts on small patches == kernel enumeration count_exact
(bit-exact for k=2 and k=3).
Output: the Omega(W,L) series, lambda(W) estimates, frontier widths,
(optional) CSV.
"""
import os, sys, math, time
import numpy as np
from itertools import product

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from rth_zint_demo import PlaneRTH                    # noqa: E402
from RTH_numerical_verification import rref_and_param  # noqa: E402

MAX_STATES = 2e8                                      # hard budget gate


class StripTM:
    def __init__(self, W, L):
        t0 = time.time()
        t = PlaneRTH(W, L)
        self.t = t
        E = t.E
        hex_idx = [fi for fi, (k, p, ft) in enumerate(t.faces) if ft == 6]
        hex_cent = {fi: np.mean(np.array(t.faces[fi][1]), axis=0) for fi in hex_idx}
        import math as _m
        D = 1.0 * (1 + _m.sqrt(3))
        B2 = np.array((0.0, D))
        B1 = np.array((D * _m.sqrt(3) / 2, D / 2))
        Minv = np.linalg.inv(np.column_stack([B1, B2]))
        self.col = {}
        for fi, (k, p, ft) in enumerate(t.faces):
            cent = np.mean(np.array(p), axis=0)
            if ft == 6:
                j = int(round((Minv @ cent)[1]))
            else:
                near = [h for h in hex_idx
                        if np.hypot(*(hex_cent[h] - cent)) < 2.0]
                assert near, f"face {fi} finds no neighboring hexagon"
                js = [int(round((Minv @ hex_cent[h])[1])) for h in near]
                j = max(js)
            self.col[fi] = j
        assert sorted(set(self.col.values())) == list(range(L)), \
            f"column-index coverage anomaly {sorted(set(self.col.values()))} vs L={L}"
        # per-edge coefficients (Z^4) and face equations
        self.edge_coef = []
        for eid in range(E):
            (cx, sy) = t.edge_cs[eid]
            self.edge_coef.append((int(2 * cx.a), int(2 * cx.b),
                                   int(2 * sy.a), int(2 * sy.b)))
        self.face_eqs = []
        for fi, (k, p, ft) in enumerate(t.faces):
            eqs = []
            for eid, sgn in t.face_edges[fi]:
                c = self.edge_coef[eid]
                eqs.append(tuple(sgn * v for v in c))
            self.face_eqs.append((fi, eqs, self.col[fi]))
        # face processing order: by column; within a column by
        # (centroid y, face type)
        order = sorted(range(t.F),
                       key=lambda fi: (self.col[fi],
                                       float(np.mean(np.array(t.faces[fi][1]), axis=0)[1]),
                                       t.faces[fi][2]))
        self.order = order
        # per-edge adjacent-face list (used for retirement decisions):
        # edge -> adjacent face ids
        self.edge_faces = {}
        for fi, eqs, cj in self.face_eqs:
            for eid, sgn in t.face_edges[fi]:
                self.edge_faces.setdefault(eid, []).append(fi)
        assert all(len(v) in (1, 2) for v in self.edge_faces.values()), \
            "edge adjacent-face count anomaly (>2)"
        self.edge_mincol = {e: min(self.col[f] for f in fs)
                            for e, fs in self.edge_faces.items()}
        self.edge_maxcol = {e: max(self.col[f] for f in fs)
                            for e, fs in self.edge_faces.items()}
        self.E = E
        self.build_time = time.time() - t0

    def frontier_after(self, j):
        """Active-edge set after column j is processed (fixed by geometry:
        touched, not retired)."""
        return sorted(e for e in self.edge_faces
                      if self.edge_mincol[e] <= j < self.edge_maxcol[e])

    def run(self, k, alpha0=0, report_every=8, max_states=MAX_STATES):
        A = range(alpha0, alpha0 + k)
        states = {(): 1}                      # intra-column intermediate states: sorted (eid,val) tuples
        frontier_max = 0
        series = []
        done = {}                             # edge -> processed adjacent-face count (cumulative over the scan)
        carry = None                          # frontier edge order matching the fixed-length key at the end of the previous column
        t0 = time.time()
        for j in range(self._nL()):
            if carry is not None:
                states = {tuple(zip(carry, st)): c for st, c in states.items()}
                carry = None
            col_faces = [fi for fi in self.order if self.col[fi] == j]
            for fi in col_faces:
                _, eqs, _ = self.face_eqs[fi]
                segs = self.t.face_edges[fi]
                eids = [eid for eid, _ in segs]
                coef = {eid: eqs[i] for i, (eid, _) in enumerate(segs)}
                new_states = {}
                for st, cnt in states.items():
                    cur = dict(st)
                    old_e = [e for e in eids if e in cur]
                    new_e = [e for e in eids if e not in cur]
                    acc0 = [0, 0, 0, 0]
                    for e in old_e:
                        m = coef[e]
                        v = cur[e]
                        for i in range(4):
                            acc0[i] += m[i] * v
                    for combo in product(A, repeat=len(new_e)):
                        acc = list(acc0)
                        for e, v in zip(new_e, combo):
                            m = coef[e]
                            for i in range(4):
                                acc[i] += m[i] * v
                        if any(acc):
                            continue
                        upd = dict(cur)
                        for e, v in zip(new_e, combo):
                            upd[e] = v
                        # retirement is done uniformly at face level (no
                        # retirement at this substitution; face level prunes
                        # by the done count)
                        nxt = tuple(sorted(upd.items()))
                        new_states[nxt] = new_states.get(nxt, 0) + cnt
                states = new_states
                for e in eids:
                    done[e] = done.get(e, 0) + 1
                # face-level retirement (drop edges whose both faces are
                # processed) + merge of equal keys
                merged = {}
                for st, c in states.items():
                    key = tuple(sorted((e, v) for e, v in st
                                       if done[e] < len(self.edge_faces[e])))
                    merged[key] = merged.get(key, 0) + c
                states = merged
                if len(states) > max_states:
                    raise MemoryError(f"state count {len(states)} exceeds gate {max_states:.0e}")
                frontier_max = max(frontier_max, len(states))
                if len(states) > max_states:
                    raise MemoryError(f"state count {len(states)} exceeds gate {max_states:.0e}")
                frontier_max = max(frontier_max, len(states))
            # end of column: fixed-order key
            fr = self.frontier_after(j)
            fixed = {}
            for st, cnt in states.items():
                d = dict(st)
                key = tuple(d[e] for e in fr)
                fixed[key] = fixed.get(key, 0) + cnt
            states = fixed
            carry = fr
            tot = sum(fixed.values())
            series.append((j + 1, tot, len(fixed), len(fr)))
            if (j + 1) % report_every == 0 or j == 0:
                lam = (math.log(tot) - math.log(series[0][1])) / (j) if j else float('nan')
                print(f"    L={j+1}: Omega={tot:.3e} states={len(fixed)} "
                      f"|cut|={len(fr)} ({time.time()-t0:.0f}s)", flush=True)
            omega_prev = tot
        return series

    def _nL(self):
        return max(self.col.values()) + 1


def anchor_check(k_list=(2, 3)):
    """Small patches: DP == kernel enumeration count_exact."""
    import verify_dsh_audit as V
    ok_all = True
    for (W, L) in ((1, 1), (1, 2), (2, 2), (2, 3), (3, 1), (3, 2)):
        t = PlaneRTH(W, L)
        T, piv, free, dim = rref_and_param(t.xrows, t.yrows, t.E)
        tm = StripTM(W, L)
        for k in k_list:
            ref = V.count_exact(T, free, t.E, k, alpha0=0)
            ser = tm.run(k, report_every=10**9)
            got = ser[-1][1]
            ok = (got == ref)
            ok_all &= ok
            print(f"  anchor W={W} L={L} k={k}: DP={got} kernel_enum={ref} "
                  f"{'PASS' if ok else 'FAIL'}", flush=True)
    return ok_all


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default="local")   # local | server
    ap.add_argument("--Ws", default="1,2,3")
    ap.add_argument("--Lmax", type=int, default=24)
    ap.add_argument("--ks", default="2")
    ap.add_argument("--skip_anchor", action="store_true")
    args = ap.parse_args()

    print(f"= strip TM (mode={args.mode}) {time.strftime('%F %T')} =", flush=True)
    if not args.skip_anchor:
        print("anchor: DP vs kernel enumeration", flush=True)
        if not anchor_check():
            print("anchor check failed; aborting", flush=True)
            return 1
        print("-" * 80, flush=True)
    out_rows = []
    for W in [int(x) for x in args.Ws.split(",")]:
        for k in [int(x) for x in args.ks.split(",")]:
            t0 = time.time()
            print(f"strip W={W} k={k}:", flush=True)
            tm = StripTM(W, args.Lmax)
            print(f"  build: V={tm.t.V} E={tm.E} F={tm.t.F} "
                  f"({tm.build_time:.0f}s)", flush=True)
            try:
                ser = tm.run(k)
            except MemoryError as e:
                print(f"  ABORT: {e}", flush=True)
                return 2
            for (L, om, ns, fr) in ser:
                out_rows.append((W, k, L, om, ns, fr))
            # lambda estimate: average over the last 4 points
            if len(ser) >= 5:
                lams = [math.log(ser[i+1][1]) - math.log(ser[i][1])
                        for i in range(len(ser) - 4, len(ser) - 1)]
                lam = math.exp(sum(lams) / len(lams))
                print(f"  ==> lambda(W={W},k={k}) ~ {lam:.4f}  "
                      f"(H1/perimeter-law prediction ~ 3.13; positive entropy "
                      f"predicts growth with W)", flush=True)
            print(f"  ({time.time()-t0:.0f}s)", flush=True)
    if args.mode == "server":
        out = os.path.join(HERE, "rth_strip_tm.csv")
        with open(out, "w") as f:
            f.write("W,k,L,omega,n_states,frontier\n")
            for r in out_rows:
                f.write(",".join(str(x) for x in r) + "\n")
        print("CSV ->", out, flush=True)
    print("done", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
