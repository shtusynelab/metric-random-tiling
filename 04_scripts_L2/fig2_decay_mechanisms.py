# -*- coding: utf-8 -*-
"""fig2_decay_mechanisms.py - main-text Fig 2: four metric-entropy decay
mechanisms (patterns + subextensive data).
a propagation (square): s = lnOmega/N_F vs L (exact perimeter law
Omega = k^(Lx+Ly), s ~ 1/L -> 0)
b spectral (kagome): exact Omega and the rank bound
s_bound = dim*ln k/N_F decay in lockstep (dim ker = Lq + Lr + gcd - 1)
c row splitting (4.8.8): Q(sqrt2) lattice ensemble lnOmega/F vs W, riding
on the Z baseline 2 ln 3 / W (subextensive)
d rigid / rank-deficient: solution dimension vs L -- 2L+1 (3.3.3.4.4, [N])
and the locked constants 2/1/0 (snub square / triangular). No area
reference (~L^2) guide line is drawn on purpose: extensivity only requires
linear growth with N_F, and a fixed-slope reference line would suggest that
one specific slope is required, which is misleading.
Pattern assets: figs/assets_decay/ (uses the Fig 1 area-coloring language --
target faces viridis by area/mean, non-target faces gray #eeeeee, uniform
heavy black edges; generated by gen_decay_assets.py:
sq_faces/kagome_faces/q488_faces/tri_faces; the older edge-colored
G2/G3/G4_* versions are archived).
Data: SQ_entropy_density_verification.csv (z4_square),
KAG_entropy_density_verification.csv (z4_kagome),
TSQ_Lambda_DP_exp.csv (z3_488).
Output: ../figs/fig2_decay_mechanisms.{png,pdf}"""
import sys
from pathlib import Path
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import paths_common as PC  # noqa: E402
# canvas not flattened -- keep the native 7.2:6.1 aspect ratio, height
# aligned with Fig 1 (6.30 in); font sizes/line widths use the Fig 1 design
# values (xK = 10.82/7.205, digit-for-digit identical to Fig 1).
K = 10.82 / 7.205
LEG_FS = 6 * K          # legend font size (slightly below the 7K body size)
from l1_style import savefig  # noqa: E402
import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import matplotlib.gridspec as gs  # noqa: E402
import matplotlib.ticker as mticker  # noqa: E402

ASSETS = PC.FIGURES / "assets_decay"

plt.rcParams.update({
    'font.size': 7 * K,
    'axes.labelsize': 7 * K,
    'legend.fontsize': 7 * K,
    'xtick.labelsize': 7 * K,
    'ytick.labelsize': 7 * K,
})
FIGS = PC.FIGURES
C_PROP = "#2166ac"
C_SPEC = "#2f6db0"
C_SPLIT = "#c0392b"
C_RIGID = "#7b3294"


def plabel(ax, s, dx=-0.08, dy=1.02):
    """Panel label at 8*K pt (matches Fig 1)."""
    ax.text(dx, dy, s, transform=ax.transAxes, fontsize=8 * K,
            fontweight='bold', va='bottom', ha='right')


def img_inset(ax, path, rect=(0.60, 0.42, 0.38, 0.55)):
    """Inset showing a pattern asset."""
    axin = ax.inset_axes(rect)
    im = plt.imread(path)
    axin.imshow(im, aspect="equal")
    axin.set_xticks([])
    axin.set_yticks([])
    for s in axin.spines.values():
        s.set_visible(False)
    return axin


def main():
    fig = plt.figure(figsize=(7.2 / 6.1 * 6.30, 6.30))   # native ratio, height = Fig 1
    G = gs.GridSpec(2, 2, figure=fig, hspace=0.28, wspace=0.24,
                    left=0.080, right=0.975, top=0.975, bottom=0.075)

    # ---- a: propagation (square) ----
    axa = fig.add_subplot(G[0, 0])
    sq = pd.read_csv(PC.engine("z4_square") /
                     PC.fname("SQ_entropy_density_verification.csv"))
    ser = sq[sq.case == "series"]
    F = ser.F.values.astype(float)                    # square torus: F = L^2
    s_sq = np.log(ser.omega_formula.values.astype(float)) / F
    axa.plot(F, s_sq, "o-", ms=3.2 * K, lw=0.8 * K, color=C_PROP)
    Fg = np.logspace(np.log10(4), np.log10(2300), 50)
    axa.plot(Fg, 2 * np.log(3) / np.sqrt(Fg), ls="--", lw=0.7 * K, color="#999999")
    axa.text(50, 2 * np.log(3) / np.sqrt(50) * 1.25,   # x=300 would fall inside
             r"$\propto N_F^{-1/2}$", fontsize=7 * K, color="#777777")
    axa.set_xscale("log")
    axa.set_yscale("log")
    axa.set_xticks([10, 100, 1000])
    axa.set_xticklabels(["10", "100", "1000"])
    axa.xaxis.set_minor_locator(mticker.NullLocator())
    axa.set_xlabel(r"$N_F$")
    axa.set_ylabel(r"$s = \ln\Omega\,/\,N_F$")
    axa.tick_params(labelsize=7 * K)
    axa.text(0.03, 0.05, r"square: $\Omega = k^{L_x+L_y}$", fontsize=7 * K,
             transform=axa.transAxes, color=C_PROP)
    img_inset(axa, ASSETS / "sq_faces.png", (0.63, 0.38, 0.34, 0.60))
    plabel(axa, "a")

    # ---- b: spectral (kagome) ----
    axb = fig.add_subplot(G[0, 1])
    kg = pd.read_csv(PC.engine("z4_kagome") /
                     PC.fname("KAG_entropy_density_verification.csv"))
    for lay, col, lab in [("C_omega_k3", C_SPEC, r"exact $\Omega$ ($k = 3$)"),
                          ("C_omega_k2", "#5b8ec4", r"exact $\Omega$ ($k = 2$)")]:
        d = kg[kg.layer == lay]
        F = d.F.values.astype(float)
        s = np.log(d.omega.values.astype(float)) / F
        dim = d.dim_formula.values.astype(float)
        kk = d.k.values.astype(float)
        axb.plot(F, s, "o", ms=3.2 * K, color=col, label=lab)
        axb.plot(F, dim * np.log(kk) / F, "_", ms=6 * K, mew=1.2 * K, color=col,
                 alpha=0.65)
    axb.plot([], [], "_", ms=6 * K, mew=1.2 * K, color="#333333",
             label=r"rank bound $k^{\dim}$")
    axb.plot([12, 12], [0.455, 0.619], ls=":", lw=0.6, color="#888888",
             zorder=0.5)   # same N_F=12, two torus shapes (4,3)/(6,2) -> different s
    axb.set_xscale("log")
    axb.set_yscale("log")
    axb.set_xticks([4, 6, 10, 20, 40])
    axb.set_xticklabels(["4", "6", "10", "20", "40"])
    axb.xaxis.set_minor_locator(mticker.NullLocator())
    axb.set_ylim(0.06, 9.0)   # raised upper limit to leave room for the top-right inset
    axb.set_xlabel(r"$N_F$")
    axb.set_ylabel(r"$s = \ln\Omega\,/\,N_F$")
    axb.tick_params(labelsize=7 * K)
    axb.text(0.03, 0.05,
             r"kagome: dim ker $= L_q{+}L_r{+}\gcd{-}1 = \mathcal{O}(L)$",
             fontsize=7 * K, transform=axb.transAxes, color=C_SPEC)
    axb.legend(fontsize=LEG_FS, frameon=False, loc="upper left")
    img_inset(axb, ASSETS / "kagome_faces.png", (0.62, 0.46, 0.36, 0.52))
    plabel(axb, "b")

    # ---- c: row splitting (4.8.8) ----
    axc = fig.add_subplot(G[1, 0])
    lam = pd.read_csv(PC.engine("z3_488") / "TSQ_Lambda_DP_exp.csv")
    F_lam = lam.F.values.astype(float)        # torus W x W: F = 2W^2
    sf = lam.lnOmega_per_F.values.astype(float)
    axc.plot(F_lam, sf, "o-", ms=3.5 * K, lw=0.9 * K, color=C_SPLIT,
             label=r"$\mathbb{Q}(\sqrt{2})$ lattice")
    Fg = np.linspace(8, 50, 50)
    axc.plot(Fg, 2 * np.log(3) * np.sqrt(2) / np.sqrt(Fg), ls="--", lw=0.7 * K,
             color="#999999",
             label=r"$\mathbb{Z}$ baseline $2\ln 3/W$, $N_F = 2W^2$")
    axc.legend(fontsize=LEG_FS, frameon=False, loc="upper right")
    axc.set_xticks([8, 18, 32, 50])
    axc.set_xticklabels(["8", "18", "32", "50"])
    axc.set_xlabel(r"$N_F$")
    axc.set_ylabel(r"$s = \ln\Omega\,/\,N_F$")
    axc.tick_params(labelsize=7 * K)
    axc.text(0.03, 0.06, r"4.8.8: $\Omega = 3^{4L}$ on $\mathbb{Z}$;"
             r" $\dim_\Lambda = 2\dim_\mathbb{R}$", fontsize=7 * K,
             transform=axc.transAxes, color=C_SPLIT)
    img_inset(axc, ASSETS / "q488_faces.png", (0.54, 0.22, 0.43, 0.62))
    plabel(axc, "c")

    # ---- d: rigid / rank-deficient ----
    axd = fig.add_subplot(G[1, 1])
    Ld = np.arange(1, 9)
    NFd = 6.0 * Ld ** 2                       # 33344 double-row-cell torus: F = 6L^2
    axd.plot(NFd, 2 * Ld + 1, "o-", ms=3.2 * K, lw=0.9 * K, color=C_RIGID,
             label=r"3.3.3.4.4: $\dim = 2L{+}1$ [N]")
    axd.axhline(2, color="#5b8ec4", lw=0.9 * K, ls="-")
    axd.axhline(1, color="#2f6db0", lw=0.9 * K, ls="-")
    axd.axhline(0, color="#999999", lw=0.9 * K, ls="-")
    # line-name labels ride on the lines with white boxes masking them (text
    # and line must not overlap). Baseline = line position - 0.40: the glyph
    # ink center sits ~on the line position; the three lines are 1.0 units
    # apart, less than the text line height, so adjacent labels must be
    # offset in x (y=1 moved to the right) or they would stack vertically.
    for yy, xlab, lab, col in [(2, 20, r"3.3.4.3.4: 2", "#5b8ec4"),
                               (1, 212, r"3.3.3.3.6: 1", "#2f6db0"),
                               (0, 20, r"triangular: 0 ($\Omega = k$)", "#777777")]:
        axd.text(xlab, yy - 0.40, lab, fontsize=7 * K, color=col,
                 bbox=dict(boxstyle="square,pad=0.06", facecolor="white",
                           edgecolor="none"))
    axd.set_xlim(0, 400)
    axd.set_ylim(-1.2, 20)     # relaxed bottom margin: the 0-line label box must fit inside
    axd.set_xticks([6, 100, 200, 300, 400])
    axd.set_xticklabels(["6", "100", "200", "300", "400"])
    axd.legend(fontsize=LEG_FS, frameon=False, loc="upper left")
    axd.set_xlabel(r"$N_F$")
    axd.set_ylabel(r"solution dimension")
    axd.tick_params(labelsize=7 * K)
    img_inset(axd, ASSETS / "elt_faces.png", (0.62, 0.16, 0.34, 0.50))
    plabel(axd, "d")

    savefig(fig, str(FIGS / "fig2_decay_mechanisms"))
    print("saved", FIGS / "fig2_decay_mechanisms.{png,pdf}")


if __name__ == "__main__":
    main()
