def hex_pts(weights, s):
    """Equiangular hexagon vertices (centred), edge length = weight*s.
    First edge heads at 90 deg, CCW. Asserts closure."""
    pts = [(0.0, 0.0)]
    for k, w in enumerate(weights):
        a = np.deg2rad(90) + np.deg2rad(60) * k
        pts.append((pts[-1][0] + s * w * np.cos(a),
                    pts[-1][1] + s * w * np.sin(a)))
    assert abs(pts[-1][0]) < 1e-8 and abs(pts[-1][1]) < 1e-8, \
        f'tile not closed: {weights}'
    gx = sum(p[0] for p in pts[:-1]) / 6
    gy = sum(p[1] for p in pts[:-1]) / 6
    return [(px - gx, py - gy) for px, py in pts[:-1]]


def polygon_area(pts):
    x = [p[0] for p in pts]
    y = [p[1] for p in pts]
    return 0.5 * abs(sum(x[i] * y[(i + 1) % len(x)] -
                         x[(i + 1) % len(x)] * y[i] for i in range(len(x))))


def closable(L):
    return (L[1] + L[2] == L[4] + L[5] and
            2 * L[0] + L[1] + L[5] == 2 * L[3] + L[2] + L[4])


def draw_poly(ax, pts, fc, ec=EDGE_GRAY, lw=0.9, z=2):
    ax.add_patch(plt.Polygon(pts, closed=True, facecolor=fc, edgecolor=ec,
                             lw=lw, zorder=z))


