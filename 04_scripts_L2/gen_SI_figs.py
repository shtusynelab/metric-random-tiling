def fig_S4():
    def d6_canon(L):
        rots = [tuple(L[k:] + L[:k]) for k in range(6)]
        m = (L[0],) + tuple(reversed(L[1:]))
        rots += [tuple(m[k:] + m[:k]) for k in range(6)]
        return min(rots)

    orb = {}
    for L in product((1, 2, 3), repeat=6):
        if closable(L):
            orb.setdefault(d6_canon(L), []).append(L)
    reps = sorted(orb, key=lambda t: (sum(t), t))
    total = sum(len(v) for v in orb.values())
    assert len(reps) == 15 and total == 45, (len(reps), total)

    s = 0.30
    radii = {t: max(max(math.hypot(px, py) for px, py in hex_pts(m, s))
                    for m in orb[t]) for t in reps}
    slot = {t: 2.0 * radii[t] + 0.55 for t in reps}
    # greedy row packing at orbit boundaries
    rows, cur, curw = [], [], 0.0
    MAXW = 28.0
    for t in reps:
        w = slot[t] * len(orb[t]) + 1.0
        if cur and curw + w > MAXW:
            rows.append(cur)
            cur, curw = [], 0.0
        cur.append(t)
        curw += w
    rows.append(cur)
    fig = plt.figure(figsize=(DOUBLE_COL, 3.2))
    ax = fig.add_axes([0.02, 0.09, 0.83, 0.88])
    ax.set_aspect('equal')
    ax.axis('off')
    areas = [polygon_area(hex_pts(t, s)) for t in reps]
    norm = Normalize(min(areas), max(areas))
    y = (len(rows) - 1) * 3.4
    for row in rows:
        x = 0.0
        for t in row:
            members = sorted(orb[t])
            for j, m in enumerate(members):
                pts = hex_pts(m, s)
                draw_poly(ax, [(px + x + j * slot[t], py + y)
                               for px, py in pts], CMAP(norm(areas[reps.index(t)])),
                          lw=0.7)
            gx = x + (len(members) - 1) * slot[t] / 2
            ax.text(gx, y + radii[t] + 0.45,
                    f'{reps.index(t) + 1}: p{sum(t)} '
                    f'x{len(members)}', fontsize=5.0, ha='center',
                    va='bottom', color='#777777')
            x += slot[t] * len(members) + 1.0
        y -= 3.6
    sm = ScalarMappable(norm=norm, cmap=CMAP)
    cax = fig.add_axes([0.87, 0.42, 0.11, 0.05])
    cb = plt.colorbar(sm, cax=cax, orientation='horizontal')
    cb.set_ticks([round(min(areas), 1), round(max(areas), 1)])
    cb.ax.tick_params(labelsize=5, width=0.5, length=1.2, pad=1.0)
    cax.set_title('tile area', fontsize=5.2, pad=1.5)
    ax.set_xlim(-1.0, 29.5)
    ax.set_ylim(-2.6, 3.6 * (len(rows) - 1) + 2.8)
    savefig(fig, str(FIGS / 'S4_tile_enumeration'))
    plt.close(fig)
    print(f'[QA] S4: {len(reps)} orbits, {total} closable hexagons, '
          f'{len(rows)} rows (sizes: {[len(orb[t]) for t in reps]})')


